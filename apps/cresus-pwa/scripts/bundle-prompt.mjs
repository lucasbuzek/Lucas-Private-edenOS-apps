// Builds src/prompt.js from the canonical CRESUS in-chat package.
// Usage:
//   node scripts/bundle-prompt.mjs ~/Desktop/CRESUS_InChat_FULL_2026-10-06.zip
//   node scripts/bundle-prompt.mjs path/to/unzipped/CRESUS_InChat_FULL
import { readdirSync, readFileSync, writeFileSync, mkdtempSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
let src = process.argv[2];
if (!src) {
  console.error('Pass the CRESUS_InChat_FULL zip or folder.');
  process.exit(1);
}

if (src.endsWith('.zip')) {
  const out = mkdtempSync(join(tmpdir(), 'cresus-'));
  execFileSync('unzip', ['-q', src, '-d', out]);
  const inner = readdirSync(out).find((d) => statSync(join(out, d)).isDirectory());
  src = inner ? join(out, inner) : out;
}

const files = readdirSync(src)
  .filter((f) => /^\d\d_.*\.(md|txt)$/.test(f))
  .sort();
if (files.length === 0) {
  console.error('No numbered CRESUS module files (00_…, 01_…) found in', src);
  process.exit(1);
}

const hash = createHash('sha256');
const parts = files.map((f) => {
  const body = readFileSync(join(src, f), 'utf8');
  hash.update(f).update(body);
  return `===== ${f} =====\n${body.trim()}`;
});

const preamble = `You are CRESUS, running as a private web agent (PWA) for a household.
The modules below are your complete operating canon. Follow them exactly.
Runtime limits of this web version: no live market data, no brokerage connections,
no file uploads, no tools. When a canon feature needs live data or a native-app
capability, say so plainly and work with what the user provides.
Never ask for or repeat full account numbers, ID numbers or passwords.
Formatting: this app renders Markdown tables, headings and lists. Lines starting with
FACT:, CALCULATION:, INFERENCE:, SCENARIO:, UNCERTAINTY: or MISSING: become labels, and the
words COMPLETE, PARTIALLY COMPARABLE, EXHAUSTED, STALE, UNVERIFIED and ESTIMATE are highlighted
as evidence states. Use them as the output contracts describe, and only when they are true.`;

const prompt = `${preamble}\n\n${parts.join('\n\n')}`;
const digest = hash.digest('hex');

writeFileSync(
  join(root, 'src/prompt.js'),
  `// GENERATED by scripts/bundle-prompt.mjs — do not edit by hand.\n` +
  `// Source modules (${files.length}): ${files.join(', ')}\n` +
  `// Canon digest: ${digest}\n` +
  `export const CRESUS_CANON_DIGEST = ${JSON.stringify(digest)};\n` +
  `export const CRESUS_SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n`
);

const approxTokens = Math.round(prompt.length / 4);
console.log(`Bundled ${files.length} modules, ~${approxTokens.toLocaleString()} tokens, digest ${digest.slice(0, 12)}`);
if (approxTokens > 20000) {
  console.warn('Warning: prompt is large. On Workers AI this uses more of the free daily allowance per message.');
}
