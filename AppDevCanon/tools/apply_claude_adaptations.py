#!/usr/bin/env python3
"""Apply transport-wording adaptations (ChatGPT -> Claude) to claude-helpers/*.md.
Run AFTER build_claude_helpers.py. Deterministic; every edit is logged to ADAPTATION_LOG.md.
Behaviour/semantics of helpers are NOT changed: only host/transport wording.
Do not touch: 'silentChatGPT' (an app feature), 'ChatGPT/OpenAI-compatible provider' (provider list), canon route notes.
"""
import glob, os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "claude-helpers")
HDR_OLD = "is the helper's own text, embedded verbatim and unmodified. Only this framing header is Claude-specific."
HDR_NEW = ("is the helper's own text, embedded verbatim EXCEPT for host/transport wording adapted from ChatGPT to Claude "
           "on 2026-10-07 (every edit is listed in ADAPTATION_LOG.md; behaviour is unchanged). Otherwise only this framing header is Claude-specific.")
EDITS = {  # file -> list of (old, new)
 "ELYSIUM.claude.md": [("Both must work entirely in ChatGPT as in-chat helper suites", "Both must work entirely in-chat (in Claude, in this Project) as in-chat helper suites")],
 "FORGEMASTER.claude.md": [("ChatGPT injects or loads this repository", "Claude injects or loads this repository"),
                           ("containing ChatGPT Project/custom-instruction surface", "containing Claude Project/custom-instruction surface")],
 "THREAD.claude.md": [("When THREAD is used in ordinary ChatGPT conversation, the active ChatGPT model", "When THREAD is used in ordinary Claude conversation, the active Claude model"),
                      ("previous ChatGPT work", "previous work (Claude chats via conversation_search/recent_chats/read_conversation, Project files via project_search; ChatGPT history only if supplied as files)")],
 "THREAD_reference.md": [("current ChatGPT environment", "current Claude environment")],
 "LINGUA.claude.md": [("COPIED INTO THE CHATGPT PROJECT INSTRUCTIONS", "COPIED INTO THE CLAUDE PROJECT INSTRUCTIONS"),
                      ("DEDICATED CHATGPT PROJECT", "DEDICATED CLAUDE PROJECT")],
 "LINGUA_reference.md": [("RECOMMENDED: CHATGPT PROJECT", "RECOMMENDED: CLAUDE PROJECT"),
                         ("copied into ChatGPT Project instructions", "copied into Claude Project instructions"),
                         ("Open the ChatGPT Project in which", "Open the Claude Project in which"),
                         ("surrounding ChatGPT/Project instructions", "surrounding Claude Project instructions")],
 "HERMES_reference.md": [("Runs inside ChatGPT or a comparable capable LLM host", "Runs inside Claude (or a comparable capable LLM host)"),
                         ("Paste into ChatGPT or another", "Paste into Claude (Project instructions) or another")],
 "MAMMON.claude.md": [("new ChatGPT conversation", "new Claude conversation")],
}
log = ["# ADAPTATION LOG - ChatGPT -> Claude wording (generated by tools/apply_claude_adaptations.py)\n",
       "Only host/transport wording changed. Run tools/build_claude_helpers.py alone to regenerate the verbatim originals.\n",
       "| File | Before | After | Occurrences |", "|---|---|---|---|"]
warn = []
for f in sorted(glob.glob(os.path.join(ROOT, "*.md"))):
    name = os.path.basename(f)
    if name in ("HELPER_REGISTRY.md", "ADAPTATION_LOG.md"): continue
    t = open(f, encoding="utf-8").read(); o = t
    for old, new in EDITS.get(name, []):
        c = t.count(old)
        if c == 0: warn.append(f"NOT FOUND in {name}: {old}"); continue
        t = t.replace(old, new); log.append(f"| {name} | {old} | {new} | {c} |")
    if t != o and HDR_OLD in t: t = t.replace(HDR_OLD, HDR_NEW)
    if t != o: open(f, "w", encoding="utf-8").write(t)
# remaining ChatGPT mentions after the framing header, for review
log.append("\n## Remaining 'ChatGPT' mentions kept on purpose or needing review (file:line)\n")
for f in sorted(glob.glob(os.path.join(ROOT, "*.md"))):
    name = os.path.basename(f)
    if name in ("HELPER_REGISTRY.md", "ADAPTATION_LOG.md"): continue
    started = name.endswith("_reference.md")
    for i, line in enumerate(open(f, encoding="utf-8").read().split("\n"), 1):
        if line.startswith("## ORIGINAL DEFINITION"): started = True
        if started and "chatgpt" in line.lower():
            log.append(f"- {name}:{i}: {line.strip()[:200]}")
log += ["", "## Warnings", *(warn or ["none"])]
open(os.path.join(ROOT, "ADAPTATION_LOG.md"), "w", encoding="utf-8").write("\n".join(log) + "\n")
print("edits logged; warnings:", len(warn)); [print(w) for w in warn]
